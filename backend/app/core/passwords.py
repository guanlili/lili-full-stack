def validate_password_not_common(password: str | None) -> str | None:
    """拒绝常见弱密码；供 pydantic field_validator 调用（ValueError → 422）。

    UserUpdate.password 等可选字段传 None 时直通，不参与校验。
    """
    if password is None:
        return password
    if password.lower() in COMMON_PASSWORDS:
        raise ValueError("Password is too common, choose a less predictable one")
    return password
